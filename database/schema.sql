CREATE TABLE IF NOT EXISTS customers (
  id text PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 150)
);
CREATE TABLE IF NOT EXISTS categories (
  id text PRIMARY KEY,
  name text NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 150)
);
CREATE TABLE IF NOT EXISTS users (
  id text PRIMARY KEY,
  name text NOT NULL,
  email text UNIQUE NOT NULL CHECK (email = lower(email)),
  password_hash text NOT NULL,
  role text NOT NULL CHECK (role IN ('Client','Operator','Agent','Admin')),
  is_active boolean NOT NULL DEFAULT true,
  customer_id text REFERENCES customers(id),
  CHECK (role <> 'Client' OR customer_id IS NOT NULL)
);
CREATE TABLE IF NOT EXISTS requests (
  id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 1044) PRIMARY KEY,
  title text NOT NULL CHECK (length(trim(title)) BETWEEN 5 AND 120),
  description text NOT NULL CHECK (length(trim(description)) BETWEEN 10 AND 3000),
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new','assigned','in_progress','waiting','resolved','closed')),
  priority text NOT NULL CHECK (priority IN ('low','medium','high','urgent')),
  customer_id text NOT NULL REFERENCES customers(id),
  category_id text NOT NULL REFERENCES categories(id),
  author_id text NOT NULL REFERENCES users(id),
  assignee_id text REFERENCES users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  due_at timestamptz,
  resolution text,
  waiting_reason text,
  closing_reason text,
  revision integer NOT NULL DEFAULT 1 CHECK (revision > 0)
);
CREATE TABLE IF NOT EXISTS comments (
  id uuid PRIMARY KEY,
  request_id integer NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  author_id text NOT NULL REFERENCES users(id),
  text text NOT NULL CHECK (length(trim(text)) BETWEEN 1 AND 2000),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS request_events (
  id uuid PRIMARY KEY,
  request_id integer NOT NULL REFERENCES requests(id) ON DELETE CASCADE,
  actor_id text REFERENCES users(id),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  kind text NOT NULL CHECK (kind IN ('created','status','comment')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  user_id text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS requests_author_idx ON requests(author_id);
CREATE INDEX IF NOT EXISTS requests_assignee_idx ON requests(assignee_id);
CREATE INDEX IF NOT EXISTS requests_status_idx ON requests(status);
CREATE INDEX IF NOT EXISTS comments_request_idx ON comments(request_id);
CREATE INDEX IF NOT EXISTS events_request_idx ON request_events(request_id);
CREATE INDEX IF NOT EXISTS sessions_expires_idx ON sessions(expires_at);
ALTER TABLE comments ADD COLUMN IF NOT EXISTS client_id uuid;
CREATE UNIQUE INDEX IF NOT EXISTS comments_client_id_idx ON comments(author_id,client_id) WHERE client_id IS NOT NULL;
